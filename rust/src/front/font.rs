//! Debug 4×6 font — stands in for the runtime-loaded glyph data the
//! `[0x1268]` slot reads from `ds:0x3009`/`ds:0x30F9` (file `0x2EECE`).
//!
//! The real table is staged by the `0x1278` load op, which isn't fully
//! decoded yet; this hand-drawn font keeps text legible meanwhile.
//! Glyphs are authored as six rows, low nibble = four pixels left→right
//! (bit 3 = leftmost). Lowercase maps to upper — the game's charset is
//! all-caps anyway.

use crate::args::Video;
use crate::video::Screen;

const W: usize = 320;
const H: usize = 200;

/// The fallback box for unmapped codes.
