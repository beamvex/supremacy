//! `menu_text` stream (`ss:` space — `dgroup.bin` file region
//! `0x202F0` maps to `ds:`-blob offset `0xFC50`) → `stream::Blk` typed
//! blocks — the `cs:0x2F629` block decoder compiled.

use super::blob::Blobs;
use super::out::Out;

/// Blob offset of the stream base (`file 0x202F0` − `0x106A0`).
const STREAM: usize = 0xFC50;

/// Byte at absolute blob index `i`.
fn by(b: &Blobs, i: usize) -> u8 {
    b.ds.get(i).copied().unwrap_or(0)
}
/// Entry offsets used by `Call::Text` in the sources.
const ENTRIES: &[u16] = &[0x5012, 0x5712, 0x578A, 0x5802, 0x587A, 0x58F2];

/// One line record: xoff byte, tile bytes, the `0xF0` arg (or none
/// when the line ends the block).
struct Line {
    xoff: u8,
    tiles: Vec<u8>,
    brk: Option<u8>,
}

/// One block: `fb` (`fb15`) + lines.
struct Blk {
    fb: u8,
    lines: Vec<Line>,
    end: bool,
    nxt: u16,
}

/// Decode from `ofs`; returns the blocks and whether the run ended
/// on `0x00`.
fn decode(b: &Blobs, ofs: u16) -> (Vec<(u16, Blk)>, bool) {
    let mut di = STREAM + usize::from(ofs);
    let mut out = Vec::new();
    loop {
        let bo = di - STREAM;
        let fb = by(b, di + 1);
        di += 2;
        let mut lines = Vec::new();
        let mut end = 0u8;
        while end == 0 {
            let xoff = by(b, di);
            di += 1;
            let mut tiles = Vec::new();
            let mut brk = None;
            loop {
                let op = by(b, di);
                di += 1;
                match op {
                    0x00 => {
                        end = 2;
                        break;
                    }
                    0xFF => {
                        end = 1;
                        break;
                    }
                    0xF0 => {
                        brk = Some(by(b, di));
                        di += 1;
                        break;
                    }
                    _ => tiles.push(op),
                }
            }
            lines.push(Line { xoff, tiles, brk });
        }
        let nxt = u16::try_from(di - STREAM).unwrap_or(0);
        out.push((
            u16::try_from(bo).unwrap_or(0),
            Blk {
                fb,
                lines,
                end: end == 2,
                nxt,
            },
        ));
        if end == 2 {
            return (out, true);
        }
    }
}

/// `Line` → Rust expr.
fn line(l: &Line) -> String {
    let t = l
        .tiles
        .iter()
        .map(|x| format!("{x:#04X}"))
        .collect::<Vec<_>>()
        .join(", ");
    let brk = l.brk.map_or("None".into(), |x| format!("Some({x:#04X})"));
    format!(
        "Line {{ xoff: {:#04X}, tiles: &[{t}], brk: {brk} }}",
        l.xoff
    )
}

/// Emit `src/front/text/stream/`.
pub fn emit(b: &Blobs, o: &mut Out) {
    let mut arms = String::new();
    let mut mods = String::new();
    let mut i = 0;
    for &e in ENTRIES {
        let (blocks, ended) = decode(b, e);
        assert!(ended, "menu_text entry {e:#06X} never ends");
        for (ofs, blk) in blocks {
            if blk.lines.is_empty() {
                continue;
            }
            let ls = blk
                .lines
                .iter()
                .map(line)
                .collect::<Vec<_>>()
                .join(",\n    ");
            let body = format!("const B{i}: Blk = Blk {{\n    fb: {:#04X},\n    end: {},\n    nxt: {:#06X},\n    lines: &[\n    {ls}\n    ],\n}};\n\npub(super) fn f(_a: u16) -> &'static Blk {{ &B{i} }}\n", blk.fb, blk.end, blk.nxt);
            o.file(&format!("front/text/stream/b{i}.rs"), &format!("//! @generated by `xgen` — menu_text block {i} (`ss:{ofs:#06X}`).\n\nuse super::{{Blk, Line}};\n\n{body}"));
            mods += &format!("mod b{i};\n");
            arms += &format!("        {ofs:#06X} => Some(b{i}::f(a)),\n");
            i += 1;
        }
    }
    let m = format!("//! @generated by `xgen` — `menu_text` stream compiled to typed\n//! blocks (`cs:0xF672`-cursor keyed).\n\n/// One line record — `xoff` byte, glyph/clear bytes, the `0xF0`\n/// line-break arg (`None` when the block ended instead).\npub struct Line {{\n    /// The line's xoff byte.\n    pub xoff: u8,\n    /// Tile ops (`0x20` clear, else glyph `op − 0x41`).\n    pub tiles: &'static [u8],\n    /// The `0xF0` break arg.\n    pub brk: Option<u8>,\n}}\n\n/// One stream block — `fb15` + line records.\npub struct Blk {{\n    /// The block's `fb15` byte.\n    pub fb: u8,\n    /// `true` when the stream ended (`0x00`) — the `ended` latch.\n    pub end: bool,\n    /// Next block offset after a `0xFF` suspend (0 when `end`).\n    pub nxt: u16,\n    /// Its line records.\n    pub lines: &'static [Line],\n}}\n\n{mods}\n/// The block at stream offset `a`.\npub fn at(a: u16) -> Option<&'static Blk> {{\n    match a {{\n{arms}        _ => None,\n    }}\n}}\n");
    o.file("front/text/stream/mod.rs", &m);
}
