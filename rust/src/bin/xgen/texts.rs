//! Print-interpreter strings — `ds:` bytes with `0x01..0x04` control
//! codes → resolved draw lists (`texttab::Dec`), compiled once here so
//! printing replays typed draws instead of fetching control bytes.
//!
//! Coverage: every `ds:` offset in the immutable `low` region
//! (`0..0x7D39`) whose shipped bytes decode a string containing at
//! least one control code. Strings without control codes — and the
//! mutable save-block text (`0x7D39..`) — need no table: they print as
//! a plain glyph run, which is what the live fallback scan does.

use super::blob::{b16, b8, Blobs};
use super::out::Out;

/// Immutable region limit — the save-block base.
const LOW_LEN: u16 = 0x7D39;
/// Decode bound per candidate offset.
const CAP: usize = 0x800;
/// Lines per emitted chunk file.
const LINES: usize = 170;

/// One emitted draw — glyph `ch` at `(bx, dx)` deltas from the entry
/// cursor, `pace` = the direct-char typewriter gate.
struct Draw {
    ch: u8,
    bx: i16,
    dx: i16,
    pace: bool,
}

/// One decoded string — its draws and the net `bx` the asm returns.
struct Dec {
    draws: Vec<Draw>,
    ctl: bool,
}

/// Decode the string at `a`; `Some` only when at least one `0x01..0x04`
/// control ran (plain strings need no table).
fn decode(b: &Blobs, a: u16) -> Option<(Dec, i16)> {
    let mut d = Dec {
        draws: Vec::new(),
        ctl: false,
    };
    let (mut bx, mut dx, mut si) = (0i32, 0i32, a);
    for _ in 0..CAP {
        let al = b8(&b.ds, si);
        si += 1;
        if al == 0xFF {
            break;
        }
        if al >= 0x20 {
            put(&mut d, al, &mut bx, dx);
            continue;
        }
        match al {
            0x01 | 0x02 => {
                let n = i32::from(b8(&b.ds, si) as i8);
                si += 1;
                if al == 0x01 {
                    dx += n;
                } else {
                    bx += n;
                }
                d.ctl = true;
            }
            0x03 | 0x04 => {
                let w = b16(&b.ds, si);
                si += 2;
                rep(&mut d, w, &mut bx, &mut dx, al == 0x04);
                d.ctl = true;
            }
            _ => break,
        }
    }
    (d.ctl && !d.draws.is_empty()).then_some((d, bx as i16))
}

/// A direct char — `pace` set, `bx += 1`.
fn put(d: &mut Dec, ch: u8, bx: &mut i32, dx: i32) {
    d.draws.push(Draw {
        ch,
        bx: *bx as i16,
        dx: dx as i16,
        pace: true,
    });
    *bx += 1;
}

/// `0x03`/`0x04` — `{count, char}`; `count ≥ 1`, no `pace`.
fn rep(d: &mut Dec, w: u16, bx: &mut i32, dx: &mut i32, vert: bool) {
    let n = (w & 0xFF).max(1) as u8;
    let ch = (w >> 8) as u8;
    for _ in 0..n {
        d.draws.push(Draw {
            ch,
            bx: *bx as i16,
            dx: *dx as i16,
            pace: false,
        });
        if vert {
            *dx += 6;
        } else {
            *bx += 1;
        }
    }
}

/// Rust expr for a [`Draw`].
fn draw(d: &Draw) -> String {
    let (ch, bx, dx, p) = (d.ch, d.bx, d.dx, d.pace);
    format!("Draw {{ ch: {ch:#04X}, bx: {bx}, dx: {dx}, pace: {p} }}")
}

/// Emit `src/game/texttab/` — `Draw`/`Dec`, `at`, `s*.rs` chunks each
/// holding their strings' consts and the `f` lookup arm.
pub fn emit(b: &Blobs, o: &mut Out) {
    let mut arms = Vec::new();
    for a in 0..LOW_LEN {
        let Some((d, bx)) = decode(b, a) else {
            continue;
        };
        let draws = d.draws.iter().map(draw).collect::<Vec<_>>().join(", ");
        let sig = (0..4)
            .map(|k| format!("{:#04X}", b8(&b.ds, a + k)))
            .collect::<Vec<_>>()
            .join(", ");
        arms.push((
            a,
            format!("const S{a:04X}: Dec = Dec {{\n    draws: &[{draws}],\n    bx: {bx},\n    sig: [{sig}],\n}};\n\n"),
            format!("        {a:#06X} => Some(&S{a:04X}),\n"),
        ));
    }
    emit_files(o, &arms);
}

/// Write the chunked `texttab` files.
fn emit_files(o: &mut Out, arms: &[(u16, String, String)]) {
    let mut mods = String::new();
    let mut calls = String::new();
    for (i, c) in arms.chunks(LINES).enumerate() {
        let decl = c.iter().map(|x| x.1.as_str()).collect::<String>();
        let am = c.iter().map(|x| x.2.as_str()).collect::<String>();
        mods += &format!("mod s{i};\n");
        calls += &format!(
            "        {:#06X}..={:#06X} => s{i}::f(a),\n",
            c[0].0,
            arms.get((i + 1) * LINES)
                .map_or(0xFFFF, |x| u32::from(x.0 - 1))
        );
        o.file(
            &format!("game/texttab/s{i}.rs"),
            &format!("//! @generated by `xgen` — decoded string chunk {i}.\n\nuse super::{{Dec, Draw}};\n\n{decl}pub(super) fn f(a: u16) -> Option<&'static Dec> {{\n    match a {{\n{am}        _ => None,\n    }}\n}}\n"),
        );
    }
    o.file("game/texttab/mod.rs", &mod_rs(&mods, &calls));
}

/// The `texttab/mod.rs` text.
fn mod_rs(mods: &str, calls: &str) -> String {
    format!("//! @generated by `xgen` — `ds:` print strings with `0x01..0x04`\n//! control codes resolved to draw lists (the `cs:0x6709` interpreter\n//! compiled). Plain strings take the live scan instead.\n\n/// One emitted glyph — char + entry-relative cursor + `pace` flag.\n#[derive(Clone, Copy)]\npub struct Draw {{\n    /// The glyph byte.\n    pub ch: u8,\n    /// `bx` delta from the entry cursor.\n    pub bx: i16,\n    /// `dx` delta from the entry cursor.\n    pub dx: i16,\n    /// The direct-char typewriter gate (repeat fills skip it).\n    pub pace: bool,\n}}\n\n/// A decoded string — draws plus the net `bx` the print returns.\npub struct Dec {{\n    /// Emitted draws, in order.\n    pub draws: &'static [Draw],\n    /// Net `bx` delta the `cs:0x6709` return carries.\n    pub bx: i16,\n}}\n\n{mods}\n/// The decoded string at `a`, if `a` holds control codes.\npub fn at(a: u16) -> Option<&'static Dec> {{\n    match a {{\n{calls}        _ => None,\n    }}\n}}\n")
}
