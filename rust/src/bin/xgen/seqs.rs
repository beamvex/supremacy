//! Draw-sequencer streams (`cs:` 4-byte `{op, pad}` records) → a
//! `seqtab::at` match mapping every reachable record address to its
//! compiled `(SeqOp, next)` pair — the `cs:0x5C52` fetch loop compiled.
//!
//! Heads come from: literal `[0x9198]` arms in the Rust sources, the
//! `cs:0x698`-table panel slots, the `ds:0x9B12` machine-type records'
//! `+0x18` field, and the ending reveal constants.

use std::collections::{BTreeMap, HashSet};

use super::blob::{b16, Blobs};
use super::out::Out;

/// Every literal stream head written into `[0x9198]` in the sources.
const HEADS: &[u16] = &[0x360, 0x3CC, 0x424, 0x9F6, 0xB22, 0xC8A, 0xA0A, 0xDBE];
/// `cs:0x698` panel table — `0xE`-byte slots, word 0 = stream head.
const PANEL_TAB: u16 = 0x698;
/// Panel slots to read (owners `0..=6`; kind-1 shares slot `0x6EC`).
const PANEL_N: u16 = 7;
/// `ds:0x9B12` machine-type records, stride `0x30`, seq field `+0x18`.
const TYPE_BASE: u16 = 0x9B12;
/// Type records to scan.
const TYPE_N: u16 = 0x10;
/// Per-head decode bound — a head that never ends or loops inside it
/// is not a stream (a stale record pointer).
const CAP: usize = 0x400;

/// The candidate head set, in decode order.
fn heads(b: &Blobs) -> Vec<u16> {
    let mut v: Vec<u16> = HEADS.to_vec();
    for i in 0..PANEL_N {
        v.push(b16(&b.cs, PANEL_TAB + i * 0xE));
    }
    for i in 0..TYPE_N {
        v.push(b16(&b.ds, TYPE_BASE + i * 0x30 + 0x18));
    }
    v
}

/// Decode every reachable record position into `addr → (op, next)`.
fn decode(b: &Blobs) -> BTreeMap<u16, (String, u16)> {
    let mut out = BTreeMap::new();
    let mut done = HashSet::new();
    for h in heads(b) {
        if h == 0 || out.contains_key(&h) || !done.insert(h) {
            continue;
        }
        walk(b, h, &mut out);
    }
    out
}

/// Follow one stream from `si`, emitting an arm per record position;
/// a head that overruns [`CAP`] contributes nothing (stale pointer).
fn walk(b: &Blobs, si: u16, out: &mut BTreeMap<u16, (String, u16)>) {
    let mut stack = vec![si];
    let mut mine = Vec::new();
    while let Some(a) = stack.pop() {
        if mine.len() > CAP {
            for m in &mine {
                out.remove(m);
            }
            eprintln!("seqs: head {si:#06X} overruns — dropped");
            return;
        }
        if out.contains_key(&a) {
            continue;
        }
        mine.push(a);
        match b16(&b.cs, a) {
            0xFFFF => {
                out.insert(a, ("SeqOp::End".into(), 0));
            }
            0x01F4 => {
                let d = b16(&b.cs, a + 4);
                out.insert(a, (format!("SeqOp::Delay({d:#06X})"), a + 8));
                stack.push(a + 8);
            }
            0 => {
                let t = b16(&b.cs, a + 4);
                out.insert(a, (format!("SeqOp::Go({t:#06X})"), t));
                stack.push(t);
            }
            img => {
                out.insert(a, (format!("SeqOp::Img({img:#06X})"), a + 4));
                stack.push(a + 4);
            }
        }
    }
}

/// Lines per emitted chunk file.
const LINES: usize = 170;

/// Emit `src/game/seqtab/` — `mod.rs` with `SeqOp` + `at`, `a*.rs`
/// arm chunks range-dispatched by their first address.
pub fn emit(b: &Blobs, o: &mut Out) {
    let tab = decode(b);
    let arms: Vec<(u16, String)> = tab
        .iter()
        .map(|(a, (op, next))| {
            (
                *a,
                format!("        {a:#06X} => Some(({op}, {next:#06X})),\n"),
            )
        })
        .collect();
    let mut mods = String::new();
    let mut calls = String::new();
    for (i, c) in arms.chunks(LINES).enumerate() {
        mods += &format!("mod a{i};\n");
        calls += &format!(
            "        {:#06X}..={:#06X} => a{i}::f(a),\n",
            c[0].0,
            arms.get((i + 1) * LINES)
                .map_or(0xFFFF, |x| u32::from(x.0 - 1))
        );
        o.file(
            &format!("game/seqtab/a{i}.rs"),
            &format!("//! @generated by `xgen` — seq arm chunk {i}.\n\nuse super::SeqOp;\n\npub(super) fn f(a: u16) -> Option<(SeqOp, u16)> {{\n    match a {{\n{}        _ => None,\n    }}\n}}\n", c.iter().map(|x| x.1.as_str()).collect::<String>()),
        );
    }
    let head = "//! @generated by `xgen` — `cs:` draw-sequencer records compiled\n//! to typed ops. `at` maps each stream cursor to `(op, next)`.\n\n/// One compiled sequencer command.\n#[derive(Clone, Copy, PartialEq, Eq, Debug)]\npub enum SeqOp {\n    /// `[0x125A]`-draw image index `n`.\n    Img(u16),\n    /// Reload `[0x91A0]` with `n`.\n    Delay(u16),\n    /// Continue the fetch at `cs:` `n` (the link record).\n    Go(u16),\n    /// `0xFFFF` — clear `[0x9198]`/`[0x919A]`.\n    End,\n}\n\n";
    // The range arms are contiguous to `0xFFFF`; when they also start
    // at `0x0000` the `_` arm is unreachable and needs the allow.
    let attr = if arms.first().is_some_and(|x| x.0 == 0) {
        "#[allow(unreachable_patterns)]\n"
    } else {
        ""
    };
    let ftr = format!("\n/// `(op, next)` at stream cursor `a`; `None` off-stream.\n{attr}pub fn at(a: u16) -> Option<(SeqOp, u16)> {{\n    match a {{\n{calls}        _ => None,\n    }}\n}}\n");
    o.file("game/seqtab/mod.rs", &format!("{head}{mods}{ftr}"));
}
